/*
 * overlay_branch_identity.sql — GENERATED ... AS IDENTITY columns in branch mode.
 *
 * Purpose:  an identity column (GENERATED ALWAYS / BY DEFAULT AS IDENTITY)
 *           takes part in the branch lifecycle like any other column.  apply
 *           must replay its stored value with OVERRIDING SYSTEM VALUE (INSERT
 *           pass) and must skip a GENERATED ALWAYS column in the UPDATE SET
 *           list — otherwise PostgreSQL rejects the replay with
 *           "cannot insert a non-DEFAULT value" / "column can only be
 *           updated to DEFAULT".
 *
 * Coverage: in-branch INSERT/UPDATE/DELETE on GENERATED ALWAYS (batch replay),
 *           GENERATED BY DEFAULT (per-row replay), and a plain-PK control
 *           table, followed by apply_branch; a non-PK identity column;
 *           discard_branch; and the negative path (an explicit value written
 *           into a GENERATED ALWAYS column is rejected by PostgreSQL itself,
 *           inside a branch too).
 *
 * Dependencies: none beyond overlay_branch.
 */

-- ===== 0. Prerequisite guard (same as the other regression files) =====
DO $$
DECLARE
  _s text := current_setting('shared_preload_libraries', true);
BEGIN
  IF _s NOT LIKE '%overlay_branch%' THEN
    RAISE EXCEPTION 'Postmaster started WITHOUT shared_preload_libraries=''overlay_branch''';
  END IF;
END $$;

-- ===== Idempotent cleanup =====
SET client_min_messages = warning;
DROP TABLE IF EXISTS public.t_id_alw CASCADE;
DROP TABLE IF EXISTS public.t_id_byd CASCADE;
DROP TABLE IF EXISTS public.t_id_none CASCADE;
DROP TABLE IF EXISTS public.t_id_npk CASCADE;
DROP EXTENSION IF EXISTS overlay_branch CASCADE;
RESET client_min_messages;

CREATE EXTENSION IF NOT EXISTS overlay_branch;
SET client_min_messages = WARNING;

-- ===== A. GENERATED ALWAYS AS IDENTITY primary key (batch replay) =====
CREATE TABLE public.t_id_alw (
    id integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    v  text
);
INSERT INTO public.t_id_alw (v) VALUES ('m1'), ('m2');
SELECT id, v FROM public.t_id_alw ORDER BY id;

SELECT overlay_branch.create_branch('br_alw') AS br_alw;
SELECT overlay_branch.use_branch('br_alw');

-- The identity value is assigned by the sequence during the branch INSERT;
-- the non-key UPDATE and the DELETE both become delta rows for apply to replay.
INSERT INTO public.t_id_alw (v) VALUES ('b3');
UPDATE public.t_id_alw SET v = 'm1-branch' WHERE id = 1;
DELETE FROM public.t_id_alw WHERE id = 2;

-- Overlay read (MAIN ⊕ delta).
SELECT id, v FROM public.t_id_alw ORDER BY id;

-- MAIN must be untouched while the branch is only staged.
SELECT overlay_branch.use_branch(NULL);
SELECT id, v FROM public.t_id_alw ORDER BY id;

SELECT overlay_branch.apply_branch('br_alw');
SELECT id, v FROM public.t_id_alw ORDER BY id;

SELECT CASE
         WHEN (SELECT string_agg(id::text||'='||v, ',' ORDER BY id)
                 FROM public.t_id_alw) = '1=m1-branch,3=b3'
         THEN 'PASS:ID_ALWAYS_APPLY'
         ELSE 'FAIL:'||COALESCE((SELECT string_agg(id::text||'='||v, ',' ORDER BY id)
                                   FROM public.t_id_alw),'NULL')
       END AS id_always_apply;

-- ===== B. GENERATED BY DEFAULT AS IDENTITY primary key (per-row replay) =====
CREATE TABLE public.t_id_byd (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    v  text
);
INSERT INTO public.t_id_byd (v) VALUES ('m1'), ('m2');

SELECT overlay_branch.create_branch('br_byd') AS br_byd;
SELECT overlay_branch.use_branch('br_byd');

INSERT INTO public.t_id_byd (v) VALUES ('b3');
UPDATE public.t_id_byd SET v = 'm1b' WHERE id = 1;
DELETE FROM public.t_id_byd WHERE id = 2;

SELECT overlay_branch.use_branch(NULL);

-- Force the legacy per-row INSERT/UPDATE passes to cover that code path too.
SET overlay_branch.apply_batch = off;
SELECT overlay_branch.apply_branch('br_byd');
SET overlay_branch.apply_batch = on;

SELECT CASE
         WHEN (SELECT string_agg(id::text||'='||v, ',' ORDER BY id)
                 FROM public.t_id_byd) = '1=m1b,3=b3'
         THEN 'PASS:ID_BYD_APPLY'
         ELSE 'FAIL:'||COALESCE((SELECT string_agg(id::text||'='||v, ',' ORDER BY id)
                                   FROM public.t_id_byd),'NULL')
       END AS id_byd_apply;

-- ===== C. Plain integer primary key (control) =====
CREATE TABLE public.t_id_none (id integer PRIMARY KEY, v text);
INSERT INTO public.t_id_none (id, v) VALUES (1, 'm1'), (2, 'm2');

SELECT overlay_branch.create_branch('br_none') AS br_none;
SELECT overlay_branch.use_branch('br_none');

INSERT INTO public.t_id_none (id, v) VALUES (3, 'b3');
UPDATE public.t_id_none SET v = 'm1b' WHERE id = 1;
DELETE FROM public.t_id_none WHERE id = 2;

SELECT overlay_branch.use_branch(NULL);
SELECT overlay_branch.apply_branch('br_none');

SELECT CASE
         WHEN (SELECT string_agg(id::text||'='||v, ',' ORDER BY id)
                 FROM public.t_id_none) = '1=m1b,3=b3'
         THEN 'PASS:PLAIN_APPLY'
         ELSE 'FAIL:'||COALESCE((SELECT string_agg(id::text||'='||v, ',' ORDER BY id)
                                   FROM public.t_id_none),'NULL')
       END AS plain_apply;

-- ===== D. Non-primary-key identity column is preserved verbatim =====
CREATE TABLE public.t_id_npk (
    k  integer PRIMARY KEY,
    id integer GENERATED ALWAYS AS IDENTITY,
    v  text
);
INSERT INTO public.t_id_npk (k, v) VALUES (1, 'm1'), (2, 'm2');

SELECT overlay_branch.create_branch('br_npk') AS br_npk;
SELECT overlay_branch.use_branch('br_npk');

INSERT INTO public.t_id_npk (k, v) VALUES (3, 'b3');
UPDATE public.t_id_npk SET v = 'm1b' WHERE k = 1;

SELECT overlay_branch.use_branch(NULL);
SELECT overlay_branch.apply_branch('br_npk');
SELECT k, id, v FROM public.t_id_npk ORDER BY k;

SELECT CASE
         WHEN (SELECT string_agg(k::text||'='||id::text||'='||v, ',' ORDER BY k)
                 FROM public.t_id_npk) = '1=1=m1b,2=2=m2,3=3=b3'
         THEN 'PASS:NONPK_IDENTITY_APPLY'
         ELSE 'FAIL:'||COALESCE((SELECT string_agg(k::text||'='||id::text||'='||v, ',' ORDER BY k)
                                   FROM public.t_id_npk),'NULL')
       END AS nonpk_identity_apply;

-- ===== E. discard_branch drops the identity-table delta, MAIN untouched =====
SELECT overlay_branch.create_branch('br_disc') AS br_disc;
SELECT overlay_branch.use_branch('br_disc');
INSERT INTO public.t_id_none (id, v) VALUES (4, 'b4');
UPDATE public.t_id_alw SET v = 'would-be-lost' WHERE id = 3;
SELECT overlay_branch.use_branch(NULL);
SELECT overlay_branch.discard_branch('br_disc');

SELECT id, v FROM public.t_id_none ORDER BY id;
SELECT id, v FROM public.t_id_alw ORDER BY id;

-- ===== F. Negative: an explicit value into a GENERATED ALWAYS column is
-- ===== rejected by PostgreSQL itself, inside a branch as well =====
SELECT overlay_branch.create_branch('br_neg') AS br_neg;
SELECT overlay_branch.use_branch('br_neg');
INSERT INTO public.t_id_alw (id, v) VALUES (99, 'x');
SELECT overlay_branch.use_branch(NULL);
SELECT overlay_branch.discard_branch('br_neg');

-- ===== Final cleanup =====
SET client_min_messages = warning;
DROP TABLE public.t_id_alw CASCADE;
DROP TABLE public.t_id_byd CASCADE;
DROP TABLE public.t_id_none CASCADE;
DROP TABLE public.t_id_npk CASCADE;
DROP EXTENSION overlay_branch CASCADE;
RESET client_min_messages;
